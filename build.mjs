import fs from "node:fs";
import {renderPage} from "./site-renderer.mjs";
const readJSON=file=>JSON.parse(fs.readFileSync(file,"utf8"));
const site=readJSON("content/site.json");
const events=fs.readdirSync("content/events").filter(x=>x.endsWith(".json")).map(x=>readJSON("content/events/"+x));
fs.rmSync("dist",{recursive:true,force:true});
fs.mkdirSync("dist",{recursive:true});
fs.cpSync("public","dist",{recursive:true});
const template=fs.readFileSync("src/index.html","utf8");
fs.writeFileSync("dist/index.html",renderPage(template,site,events),"utf8");
fs.writeFileSync("dist/_osc_template.html",template,"utf8");
console.log("Built Our Stage website with "+events.length+" event cards");
